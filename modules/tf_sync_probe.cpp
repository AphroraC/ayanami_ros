// tf_sync_probe: TF sync stress-test probe extension (multi-edge version).
//
// Loaded in-process into ayanami_rosnode via AyanamiROS's extension_modules;
// polls a set of edges of the core-side TransformStore (fast_tf) at a fixed
// rate (latest queries) and records each edge's (value, core latest sample
// stamp) changes as an events CSV. Together with tf_sync_publisher.py (which
// encodes seq into each edge's translation.x) and the offline analysis of
// tf_sync_stress_test.sh, it measures the ROS TF -> ayanami core sync rate and
// latency.
//
// Configuration (config_ros.json::tf_sync_probe):
//   edges        [[target, source], ...] aligned with the publisher's
//                edge_idx order
//   poll_hz      polling rate (default 2000)
//   events_path  events CSV output (edge,x,core_stamp_ns,wall)
//   ready_path   ready marker file written after the first successful lookup

#include <ayanami/interfaces/transform_store.hpp>
#include <ayanami/utility/config.hpp>
#include <ayanami/utility/extension_module.hpp>

#include <ros/ros.h>

#include <Eigen/Geometry>

#include <atomic>
#include <chrono>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <string>
#include <thread>
#include <vector>

namespace {

using ayanami::interfaces::TransformStore;

struct ProbeConfig {
  std::vector<std::pair<std::string, std::string>> edges;
  double poll_hz{2000.0};
  std::string events_path{"/dev/shm/tf_sync_stress/events.csv"};
  std::string ready_path{"/dev/shm/tf_sync_stress/probe_ready"};
};

ProbeConfig readProbeConfig() {
  ProbeConfig cfg;
  const std::string path = ayanami::GlobalConfig::getConfigPath("config_ros");
  if (path.empty()) {
    ROS_WARN("tf_sync_probe: empty config_ros path");
    return cfg;
  }
  // The test config is generated by the driver script before the node starts;
  // if the probe reads the transient pre-generation state (empty edge list),
  // re-read every second until a non-empty edge list is obtained (up to 60s).
  for (int attempt = 0; attempt < 60; ++attempt) {
    ayanami::Config config(path);
    cfg.poll_hz =
        config.param<double>("tf_sync_probe", "poll_hz", cfg.poll_hz);
    cfg.events_path = config.param<std::string>(
        "tf_sync_probe", "events_path", cfg.events_path);
    cfg.ready_path =
        config.param<std::string>("tf_sync_probe", "ready_path", cfg.ready_path);
    const auto raw = config.param<std::vector<std::vector<std::string>>>(
        "tf_sync_probe", "edges", {});
    cfg.edges.clear();
    for (const auto& e : raw) {
      if (e.size() == 2) {
        cfg.edges.emplace_back(e[0], e[1]);
      }
    }
    if (!cfg.edges.empty()) {
      ROS_INFO("tf_sync_probe: config path='%s' edges=%zu (attempt %d)",
               path.c_str(), cfg.edges.size(), attempt);
      return cfg;
    }
    ROS_WARN("tf_sync_probe: edges empty (attempt %d, path=%s)", attempt,
             path.c_str());
    std::this_thread::sleep_for(std::chrono::seconds(1));
  }
  ROS_ERROR("tf_sync_probe: no edges after 60s, monitoring nothing");
  return cfg;
}

class TfSyncProbe final : public ayanami::ExtensionModule {
 public:
  TfSyncProbe() {
    config_ = readProbeConfig();
    std::error_code ec;
    std::filesystem::create_directories(
        std::filesystem::path(config_.events_path).parent_path(), ec);
    std::filesystem::create_directories(
        std::filesystem::path(config_.ready_path).parent_path(), ec);
    events_.open(config_.events_path, std::ios::trunc);
    if (events_.is_open()) {
      events_ << "edge,x,core_stamp_ns,wall\n";
      events_ << std::fixed;
    } else {
      ROS_ERROR("tf_sync_probe: cannot open events file %s",
                config_.events_path.c_str());
    }
    state_.assign(config_.edges.size(), {});
    running_.store(true);
    thread_ = std::thread([this] { pollLoop(); });
    ROS_INFO("tf_sync_probe: monitoring %zu edges at %.0f Hz -> %s",
             config_.edges.size(), config_.poll_hz, config_.events_path.c_str());
  }

  ~TfSyncProbe() override {
    running_.store(false);
    if (thread_.joinable()) {
      thread_.join();
    }
  }

 private:
  struct EdgeState {
    double x{0.0};
    long long stamp_ns{-1};
    bool has{false};
  };

  void pollLoop() {
    const auto period = std::chrono::microseconds(
        static_cast<long long>(1e6 /
                               (config_.poll_hz > 0.0 ? config_.poll_hz : 2000.0)));
    bool ready_signalled = false;
    double cycle_us_acc = 0.0;
    double cycle_us_max = 0.0;
    int cycle_count = 0;
    auto cycle_start = std::chrono::steady_clock::now();
    while (running_.load()) {
      for (std::size_t e = 0; e < config_.edges.size(); ++e) {
        const auto& [target, source] = config_.edges[e];
        Eigen::Isometry3d transform = Eigen::Isometry3d::Identity();
        if (!TransformStore::instance().lookupTransform(
                target, source, ayanami::Timestamp::latest(), transform, 0.0)) {
          continue;
        }
        if (!ready_signalled) {
          ready_signalled = true;
          std::ofstream ready(config_.ready_path, std::ios::trunc);
          ready << "ok\n";
        }
        const double x = transform.translation().x();
        ayanami::Timestamp core_stamp;
        TransformStore::instance().latestCommonTime(target, source, core_stamp);
        auto& st = state_[e];
        if (!st.has || x != st.x || core_stamp.count() != st.stamp_ns) {
          st.x = x;
          st.stamp_ns = core_stamp.count();
          st.has = true;
          if (events_.is_open()) {
            events_ << e << ',' << std::setprecision(12) << x << ','
                    << core_stamp.count() << ',' << std::setprecision(9)
                    << ros::WallTime::now().toSec() << '\n';
            events_.flush();
          }
        }
      }
      const auto cycle_end = std::chrono::steady_clock::now();
      const double us = std::chrono::duration<double, std::micro>(
                            cycle_end - cycle_start).count();
      cycle_us_acc += us;
      cycle_us_max = std::max(cycle_us_max, us);
      ++cycle_count;
      if (cycle_count >= 2000) {
        ROS_INFO("tf_sync_probe: cycle avg=%.0fus max=%.0fus over %d cycles",
                 cycle_us_acc / cycle_count, cycle_us_max, cycle_count);
        cycle_us_acc = 0.0;
        cycle_us_max = 0.0;
        cycle_count = 0;
      }
      cycle_start = std::chrono::steady_clock::now();
      std::this_thread::sleep_for(period);
    }
  }

  ProbeConfig config_;
  std::vector<EdgeState> state_;
  std::ofstream events_;
  std::atomic<bool> running_{false};
  std::thread thread_;
};

}  // namespace

extern "C" ayanami::ExtensionModule* create_extension_module() {
  return new TfSyncProbe();
}
